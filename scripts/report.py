"""Writes the campaign report, REPORT.md, from the campaign's own files: the same sections for every agent, so
two agents' runs can be compared row by row and no tokens are spent writing numbers by hand.

Sections: what was done and when (from run.log), the numbers, the first lines (how many the agent wrote,
how many the code rejected and why, from line_rejections.jsonl), what was taken out or moved to another
sector, the exact errors, the quality of the lines that passed (quality.py) and three sample emails.
The agent's own sections, "## Agent notes" (and "## Cost" when asked), are kept as they are between runs.

Usage: python3 report.py --campaign fl-broward
"""
import argparse
import collections
import datetime as dt
import re

from common import add_profile_arg, campaign_dir, read_jsonl
from quality import Vocabulary, problems

KEEP = ('## Agent notes', '## Cost')


def log_lines(camp) -> list[tuple[str, str]]:
    path = camp / 'run.log'
    out = []
    for line in (path.read_text(encoding='utf-8').splitlines() if path.exists() else []):
        m = re.match(r'(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d) (.*)', line)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def _lines(path) -> list[str]:
    return [l.strip() for l in path.read_text(encoding='utf-8').splitlines() if l.strip()] if path.exists() else []


def main() -> None:
    ap = argparse.ArgumentParser(description='Write REPORT.md for a campaign from its own files.')
    add_profile_arg(ap)
    ap.add_argument('--campaign', required=True)
    a = ap.parse_args()
    camp = campaign_dir(a.campaign)
    log = log_lines(camp)
    cands = read_jsonl(camp / 'candidates.jsonl')
    scan = read_jsonl(camp / 'scan.jsonl')
    leads = read_jsonl(camp / 'leads.jsonl')
    drafts = {d['id']: d for d in read_jsonl(camp / 'drafts.jsonl')}
    exported = read_jsonl(camp / 'exported.jsonl')
    manual = read_jsonl(camp / 'manual_lines.jsonl')
    rejects = read_jsonl(camp / 'line_rejections.jsonl')
    verif = (camp / 'VERIFICATION.md').read_text(encoding='utf-8') if (camp / 'VERIFICATION.md').exists() else ''
    result = re.search(r'RESULT: (\w+)', verif)
    removed, resectored = _lines(camp / 'remove.txt'), _lines(camp / 'change_sector.txt')
    started, ended = (log[0][0], log[-1][0]) if log else ('?', '?')
    mins = ''
    if log:
        t0, t1 = (dt.datetime.fromisoformat(x) for x in (started, ended))
        mins = f' ({round((t1 - t0).total_seconds() / 60)} minutes)'
    states = collections.Counter(l['status'] for l in leads)
    ok_scan = sum(1 for s in scan if s.get('read_status') == 'ok')
    new = [drafts[e['id']] for e in exported if e['id'] in drafts and not drafts[e['id']].get('pending')]
    emails = [d for d in new if d['channel'] == 'email']
    forms = [d for d in drafts.values() if not d.get('pending') and d.get('channel') == 'form']
    active = {l.get('id') for l in leads if l['status'] in ('to_draft', 'form', 'queued')}
    drafts = {k: d for k, d in drafts.items() if k in active}  # companies taken out later don't count
    vocab = Vocabulary(camp)
    lines_all = [d['first_line'] for d in drafts.values() if not d.get('pending')]
    weak = [(d, problems(d['first_line'], d['proof'], d['name'], [x for x in lines_all if x != d['first_line']], vocab, d['domain']))
            for d in drafts.values() if not d.get('pending')]
    weak = [(d, p) for d, p in weak if p]
    reasons = collections.Counter(r['reason'].split(':')[0].split('(')[0].strip()[:70] for r in rejects)
    errors = [f'{t} {m}' for t, m in log if re.search(r'FAILED|failed|error|Error|could not', m)]
    md = [f'# Report of campaign {a.campaign}', '',
          f'Generated by `report.py` on {dt.datetime.now().strftime("%Y-%m-%d %H:%M")}. The numbers come from the campaign files.', '',
          '## What was done and when', '',
          f'- First and last entry of the log: {started} -> {ended}{mins}.',
          f'- Verification: **RESULT: {result.group(1) if result else "not run"}**.', '',
          '## Numbers', '', '| Step | How many |', '|---|---|',
          f'| Companies found in this campaign | {len(cands)} |', f'| Sites read | {len(scan)} ({ok_scan} fine) |',
          f'| Companies evaluated | {len(leads)} |', f'| New emails that passed the filter | {len(emails)} |',
          f'| Forms | {len(forms)} |', '',
          'Evaluated by status: ' + ', '.join(f'{k} {v}' for k, v in states.most_common()), '',
          '## First lines', '',
          f'- Written by the agent: **{len(manual)}**.',
          f'- Rejected by the code before passing: **{len(rejects)}**'
          + (f' (from {len({r["id"] for r in rejects})} companies)' if rejects else '') + '.']
    md += [f'  - {n} x {k}' for k, n in reasons.most_common(6)]
    md += [f'- Accepted lines that the quality check marks as weak today: **{len(weak)}**.']
    md += [f'  - {d["id"]} {d["name"]}: {p[0][:110]}' for d, p in weak[:8]]
    md += ['', '## Taken out or moved to another sector', '',
           f'- Removed by hand (remove.txt): {len(removed)}' + (': ' + ', '.join(removed[:15]) if removed else ''),
           f'- Moved to another sector (change_sector.txt): {len(resectored)}' + (': ' + '; '.join(resectored[:15]) if resectored else ''), '',
           '## Errors', ''] + ([f'- `{e}`' for e in errors[:15]] or ['- None in the log.'])
    md += ['', '## Three sample emails', '']
    for d in emails[:3]:
        md += [f'### {d["name"]} | {d["to"]}', f'Subject: {d["subject"]}', '', '```', d['body'], '```', '']
    old = (camp / 'REPORT.md').read_text(encoding='utf-8') if (camp / 'REPORT.md').exists() else ''
    kept = []
    for head in KEEP:
        m = re.search(re.escape(head) + r'.*?(?=\n## |\Z)', old, re.S)
        kept.append(m.group(0).rstrip() if m else f'{head}\n\n(Written by the agent.)')
    (camp / 'REPORT.md').write_text('\n'.join(md) + '\n\n' + '\n\n'.join(kept) + '\n', encoding='utf-8')
    print(f'REPORT.md written: {len(emails)} emails, {len(forms)} forms, {len(rejects)} rejected lines, {len(weak)} weak')


if __name__ == '__main__':
    main()
