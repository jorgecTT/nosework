"""Where we have already searched, how much each search gave, and where to search next.

Reads every campaign in data/ (sources_done.json, candidates.jsonl, leads.jsonl, exported.jsonl) and writes
data/COVERAGE.md, data/coverage.json and data/READ_FIRST.md:
  - by state and county: which sectors were searched (OpenStreetMap, Brave), companies found, read, with
    email, queued;
  - which sectors give the most queued emails per site read (so the next campaign starts with those);
  - the next searches to run: counties in the order of references/regions.json, with the active sectors not
    searched there yet, best-yielding sectors first, as ready-to-paste commands.
discover.py also reads it: a county and sector already searched in any campaign is never searched again.
Run it before choosing a new campaign. Usage: python3 coverage.py [--next 5]
"""
import argparse
import json

from common import DATA, ROOT, add_profile_arg, campaigns, domain, load_sectors, read_jsonl

REGIONS = json.loads((ROOT / 'references' / 'regions.json').read_text(encoding='utf-8'))['states']


def searched() -> dict:
    """{(state, county, sector): {'osm': campaign, 'brave': campaign}} for every search done anywhere."""
    done = {}
    for camp in campaigns():
        f = camp / 'sources_done.json'
        if not f.exists():
            continue
        for key in json.loads(f.read_text(encoding='utf-8')):
            src, state, county, sector = key.split('|')
            done.setdefault((state, county, sector), {})[src] = camp.name
    return done


def yields() -> tuple[dict, dict]:
    """Per (state, county, sector) and per sector: found, read ok, with email, queued."""
    cell, by_sector = {}, {}
    for camp in campaigns():
        cands = read_jsonl(camp / 'candidates.jsonl')
        scanned = {r['domain']: r for r in read_jsonl(camp / 'scan.jsonl')}
        leads = {l['domain']: l for l in read_jsonl(camp / 'leads.jsonl')}
        queued = {r['domain'] for r in read_jsonl(camp / 'exported.jsonl')}
        for c in cands:
            d = domain(c['site'])
            k = (c['state'], c['county'], c['sector'])
            sec = leads.get(d, {}).get('sector', c['sector'])
            for key, bucket in ((k, cell), (sec, by_sector)):
                y = bucket.setdefault(key, {'found': 0, 'read': 0, 'with_email': 0, 'queued': 0})
                y['found'] += 1
                y['read'] += scanned.get(d, {}).get('read_status') == 'ok'
                y['with_email'] += leads.get(d, {}).get('channel') == 'email'
                y['queued'] += d in queued
    return cell, by_sector


def rate(y: dict) -> float:
    return y['queued'] / y['read'] if y.get('read') else -1


def contacts_summary() -> list[str]:
    import contacts
    rows = contacts.rebuild()  # the register first, so "already contacted" is today's, not last week's
    count = {}
    for r in rows:
        count[r['status'] or '-'] = count.get(r['status'] or '-', 0) + 1
    md = [f'Contacts register: **{len(rows)}** in `data/contacts.csv`. Nobody who is there as queued, sent, replied, '
          'auto_reply, bounced or blocked gets a first email again. Also respected: `data/suppress.txt` and every CSV in `data/imports/`.', '',
          '| Status | Contacts |', '|---|---|']
    return md + [f'| {k} | {v} |' for k, v in sorted(count.items(), key=lambda x: -x[1])] + ['']


def slug_of(state: str, county: str) -> str:
    return f"{state.lower()}-{county.lower().replace(' county', '').replace(' ', '-')}"


def main() -> None:
    ap = argparse.ArgumentParser(description='Where we searched, what each search gave, and where to search next.')
    add_profile_arg(ap)
    ap.add_argument('--next', type=int, default=5, help='how many next searches to recommend')
    a = ap.parse_args()
    DATA.mkdir(parents=True, exist_ok=True)
    done = searched()
    cell, by_sector = yields()
    sectors = [s for s in load_sectors() if s.get('active', True)]

    # Sectors ranked: measured yield first (needs 10 sites read to count), then the priority in sectors.json.
    def sector_key(s):
        y = by_sector.get(s['id'])
        measured = rate(y) if y and y['read'] >= 10 else None
        return (0 if measured is not None else 1, -(measured or 0), s.get('priority', 3))
    ranked = sorted(sectors, key=sector_key)
    nxt = []
    for st, region in REGIONS.items():
        for c in region['counties']:
            missing = [s['id'] for s in ranked if 'osm' not in done.get((st, c['county'], s['id']), {})
                       or 'brave' not in done.get((st, c['county'], s['id']), {})]
            if missing:
                nxt.append((st, c['county'], missing))
    md = ['# Where we already searched and where to go on', '', 'Generated by `scripts/coverage.py`. '
          'A search (county + sector + source) already done in any campaign is not repeated.', '',
          '## Already searched', '', '| State | County | Sector | Sources | Found | Read | With email | Queued |', '|---|---|---|---|---|---|---|---|']
    for (st, county, sec), srcs in sorted(done.items()):
        y = cell.get((st, county, sec), {'found': 0, 'read': 0, 'with_email': 0, 'queued': 0})
        md.append(f"| {st} | {county} | {sec} | {', '.join(sorted(srcs))} | {y['found']} | {y['read']} | {y['with_email']} | {y['queued']} |")
    md += ['', '## Which sectors give the most', '', 'Emails queued per 100 sites read (counts from 10 sites read).', '',
           '| Sector | Read | Queued | Per 100 |', '|---|---|---|---|']
    for s in ranked:
        y = by_sector.get(s['id'])
        if y and y['read']:
            md.append(f"| {s['id']} | {y['read']} | {y['queued']} | {round(100 * rate(y))}{'' if y['read'] >= 10 else ' (few so far)'} |")
    unread = []
    for camp in campaigns():
        seen = {r['domain'] for r in read_jsonl(camp / 'scan.jsonl')}
        left = [c for c in read_jsonl(camp / 'candidates.jsonl') if domain(c['site']) not in seen]
        if left:
            unread.append((camp.name, len(left)))
    if unread:
        md += ['', '## First: companies already found that are still unread', '',
               'This is the cheapest work: the search is done. Finish those campaigns before opening another.', '']
        for name, n in unread:
            md += [f'- **{name}**: {n} unread', '', '```bash', f'python3 prospect.py --campaign {name} --from scan --max 300', '```', '']
    md += ['', '## Recommended next searches', '']
    for st, county, missing in nxt[:a.next]:
        md += [f'### {county}, {st}', f'Sectors not searched yet, best first: {", ".join(missing)}', '', '```bash',
               f'python3 prospect.py --campaign {slug_of(st, county)} --state {st} --counties "{county}" --sectors {",".join(missing[:6])} --max 300',
               '```', '']
    (DATA / 'COVERAGE.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    read_first = ['# Read me first (nosework)', '',
                  'Generated by `scripts/coverage.py`. **Any agent reads this before searching anything.** '
                  'Everything needed to avoid repeating and avoid inventing is here or in the files it names.', '',
                  '## 1. Whom we already wrote to', ''] + contacts_summary()
    read_first += ['## 2. What to do now, in this order', '']
    step = 1
    for name, n in unread:
        read_first += [f'{step}. Read the **{n}** companies that campaign **{name}** already found and has not read:', '', '```bash',
                       f'cd {ROOT / "scripts"} && python3 prospect.py --campaign {name} --from scan --max 300', '```', '']
        step += 1
    for st, county, missing in nxt[:3]:
        read_first += [f'{step}. Search **{county}, {st}** for the sectors still missing ({", ".join(missing[:6])}):', '', '```bash',
                       f'cd {ROOT / "scripts"} && python3 prospect.py --campaign {slug_of(st, county)} --state {st} --counties "{county}" --sectors {",".join(missing[:6])} --max 300',
                       '```', '']
        step += 1
    read_first += ['## 3. What was searched and what each sector yields', '', 'Full detail in `data/COVERAGE.md`.', '',
                   '## 4. Rules that are not up for discussion', '',
                   '- Never write to anyone in `contacts.csv` as queued, sent, replied, auto_reply, bounced or blocked, nor to anyone on `suppress.txt` or in `data/imports/`. The scripts already prevent it: do not work around it.',
                   '- The first line of every email is written by you (the agent running the skill), never another model or an API.',
                   "- You send nothing. Sending is the user's decision, with their own tool.",
                   "- Everything else: `SKILL.md`, `references/RULES.md` and the profile's own rules.", '']
    (DATA / 'READ_FIRST.md').write_text('\n'.join(read_first), encoding='utf-8')
    (DATA / 'coverage.json').write_text(json.dumps({
        'searched': [{'state': k[0], 'county': k[1], 'sector': k[2], 'sources': sorted(v), **cell.get(k, {})} for k, v in sorted(done.items())],
        'by_sector': {str(k): v for k, v in by_sector.items()}, 'unread': [{'campaign': c, 'companies': n} for c, n in unread],
        'next': [{'state': s, 'county': c, 'sectors': m} for s, c, m in nxt[:a.next]]}, ensure_ascii=False, indent=1), encoding='utf-8')
    if unread:
        print('First, what is still unread: ' + ', '.join(f'{c} ({n})' for c, n in unread))
    print(f'{len(done)} searches done. Next recommended: '
          + (f'{nxt[0][1]}, {nxt[0][0]} ({", ".join(nxt[0][2][:6])})' if nxt else 'nothing left in regions.json')
          + f' -> {DATA / "READ_FIRST.md"}')


if __name__ == '__main__':
    main()
